#!/usr/bin/env python3
"""Builds the voice lines the clip plays through its speaker from the recordings in sounds/.

Converts each recording to 16 kHz mono 16-bit, trims the silence around it, evens out the
loudness, and writes all of them as C arrays in lib/earshot_sounds/src/. Run it again after
changing a recording or SOUNDS:

    python3 tools/make_sounds.py

Needs macOS (`afconvert`). The generated files are committed, so nobody else has to run it.
The order of SOUNDS must match earshot::Sound in lib/earshot_core/src/hal.h.
"""
import array
import subprocess
import sys
import tempfile
import wave
from pathlib import Path

SOUNDS = [                   # (C name, file in sounds/)
    ("Recording", "recording.mp3"),
    ("Paused", "paused.mp3"),
    ("Marked", "marked.mp3"),
    ("NewCall", "new-call.mp3"),
    ("CallEnded", "call-ended.mp3"),
    ("ReportReady", "report-ready.mp3"),
    ("NoTablet", "no-tablet.mp3"),
    ("ClipConnected", "clip-connected.mp3"),
    ("ClipDisconnected", "clip-disconnected.mp3"),
    ("ClipLost", "clip-lost.mp3"),
    ("ClipBack", "clip-back.mp3"),
]
RATE = 16000
PEAK = 0.9                   # of full scale, for every recording, so they play equally loud
THRESHOLD = 300              # samples below this, at either end, count as silence
FADE_S = 0.005               # short fade in and out, so the cut does not click


def load(path, tmp):
    wav = Path(tmp) / "s.wav"
    subprocess.run(["afconvert", "-f", "WAVE", "-d", f"LEI16@{RATE}", "-c", "1", str(path), str(wav)], check=True)
    with wave.open(str(wav)) as w:
        assert w.getframerate() == RATE and w.getnchannels() == 1 and w.getsampwidth() == 2
        pcm = array.array("h", w.readframes(w.getnframes()))
    loud = [i for i, s in enumerate(pcm) if abs(s) > THRESHOLD]
    pcm = pcm[max(0, loud[0] - 160):loud[-1] + 160]   # keep 10 ms either side
    gain = PEAK * 32767 / (max(abs(s) for s in pcm) or 1)
    fade = int(FADE_S * RATE)
    out = array.array("h")
    for i, s in enumerate(pcm):
        g = gain * min(1.0, i / fade, (len(pcm) - 1 - i) / fade)
        out.append(max(-32768, min(32767, int(s * g))))
    return out


def main():
    root = Path(__file__).resolve().parent.parent
    out_dir = root / "lib" / "earshot_sounds" / "src"
    out_dir.mkdir(parents=True, exist_ok=True)
    body, table, total = [], [], 0
    with tempfile.TemporaryDirectory() as tmp:
        for name, file in SOUNDS:
            pcm = load(root / "sounds" / file, tmp)
            total += len(pcm)
            print(f"{file:22s} {len(pcm) / RATE:.2f} s")
            lines = [", ".join(str(v) for v in pcm[i:i + 16]) for i in range(0, len(pcm), 16)]
            body.append(f"static const int16_t k{name}[] = {{\n    " + ",\n    ".join(lines) + "\n};\n")
            table.append(f"    {{k{name}, {len(pcm)}, \"{file}\"}},")
    (out_dir / "sounds_data.c").write_text(
        "// Generated by tools/make_sounds.py from the recordings in sounds/. Do not edit.\n"
        '#include "sounds_data.h"\n\n' + "\n".join(body) +
        "\nconst SoundClip kSoundClips[] = {\n" + "\n".join(table) + "\n};\n\n"
        f"const size_t kSoundClipCount = {len(SOUNDS)};\n")
    (out_dir / "sounds_data.h").write_text(
        "// Generated by tools/make_sounds.py from the recordings in sounds/. Do not edit.\n"
        "// Voice lines, 16 kHz mono 16-bit PCM, in the order of earshot::Sound\n"
        "// (lib/earshot_core/src/hal.h).\n"
        "#pragma once\n#include <stddef.h>\n#include <stdint.h>\n\n"
        "#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n"
        f"#define SOUND_SAMPLE_RATE {RATE}\n\n"
        "typedef struct {\n  const int16_t* samples;\n  size_t count;\n  const char* file;\n} SoundClip;\n\n"
        "extern const SoundClip kSoundClips[];\n"
        "extern const size_t kSoundClipCount;\n\n"
        "#ifdef __cplusplus\n}\n#endif\n")
    print(f"{total / RATE:.1f} s, {total * 2:,} bytes in all; wrote {out_dir}/sounds_data.c and .h")


if __name__ == "__main__":
    sys.exit(main())
