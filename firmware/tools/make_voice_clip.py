#!/usr/bin/env python3
"""Builds the voice recording that the firmware can play in place of a microphone.

Speaks SCRIPT with a macOS voice, converts it to 16 kHz mono, compresses it 4:1 with IMA ADPCM
and writes it as a C array in lib/earshot_voice/src/. Run it again after changing SCRIPT:

    python3 tools/make_voice_clip.py

Needs macOS (`say`, `afconvert`). The generated files are committed, so nobody else has to run it.
"""
import array
import subprocess
import sys
import tempfile
import wave
from pathlib import Path

VOICE = "Samantha"
SCRIPT = (
    "Sixty eight year old male with chest pain for thirty minutes, radiating to the left arm. "
    "Blood pressure is one fifty over ninety. Heart rate is one hundred and four. "
    "Aspirin given at fourteen ten."
)
RATE = 16000
LEAD_S, TAIL_S = 0.3, 1.2   # silence before the speech, and before it starts again
PEAK = 0.6                  # of full scale

STEP = [7, 8, 9, 10, 11, 12, 13, 14, 16, 17, 19, 21, 23, 25, 28, 31, 34, 37, 41, 45, 50, 55, 60,
        66, 73, 80, 88, 97, 107, 118, 130, 143, 157, 173, 190, 209, 230, 253, 279, 307, 337, 371,
        408, 449, 494, 544, 598, 658, 724, 796, 876, 963, 1060, 1166, 1282, 1411, 1552, 1707,
        1878, 2066, 2272, 2499, 2749, 3024, 3327, 3660, 4026, 4428, 4871, 5358, 5894, 6484, 7132,
        7845, 8630, 9493, 10442, 11487, 12635, 13899, 15289, 16818, 18500, 20350, 22385, 24623,
        27086, 29794, 32767]
INDEX_STEP = [-1, -1, -1, -1, 2, 4, 6, 8, -1, -1, -1, -1, 2, 4, 6, 8]


def decode_nibble(n, pred, index):
    step = STEP[index]
    diff = step >> 3
    if n & 4: diff += step
    if n & 2: diff += step >> 1
    if n & 1: diff += step >> 2
    pred = pred - diff if n & 8 else pred + diff
    pred = max(-32768, min(32767, pred))
    index = max(0, min(88, index + INDEX_STEP[n]))
    return pred, index


def encode(samples):
    """IMA ADPCM, two samples per byte, low nibble first, from predictor 0 and index 0."""
    pred, index, nibbles = 0, 0, []
    for s in samples:
        step = STEP[index]
        diff = s - pred
        n = 8 if diff < 0 else 0
        diff = abs(diff)
        if diff >= step: n |= 4; diff -= step
        if diff >= step >> 1: n |= 2; diff -= step >> 1
        if diff >= step >> 2: n |= 1
        nibbles.append(n)
        pred, index = decode_nibble(n, pred, index)
    if len(nibbles) % 2: nibbles.append(0)
    return bytes(nibbles[i] | (nibbles[i + 1] << 4) for i in range(0, len(nibbles), 2))


def decode(data):
    pred, index, out = 0, 0, array.array("h")
    for b in data:
        for n in (b & 15, b >> 4):
            pred, index = decode_nibble(n, pred, index)
            out.append(pred)
    return out


def main():
    root = Path(__file__).resolve().parent.parent
    out_dir = root / "lib" / "earshot_voice" / "src"
    out_dir.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        aiff, wav = Path(tmp) / "v.aiff", Path(tmp) / "v.wav"
        subprocess.run(["say", "-v", VOICE, "-o", str(aiff), SCRIPT], check=True)
        subprocess.run(["afconvert", "-f", "WAVE", "-d", f"LEI16@{RATE}", "-c", "1", str(aiff), str(wav)], check=True)
        with wave.open(str(wav)) as w:
            assert w.getframerate() == RATE and w.getnchannels() == 1 and w.getsampwidth() == 2
            speech = array.array("h", w.readframes(w.getnframes()))
    peak = max(abs(s) for s in speech) or 1
    gain = PEAK * 32767 / peak
    pcm = array.array("h", [0] * int(LEAD_S * RATE))
    pcm.extend(int(s * gain) for s in speech)
    pcm.extend([0] * int(TAIL_S * RATE))
    while len(pcm) % 320: pcm.append(0)   # whole 20 ms frames, so the loop point lands on a frame edge

    data = encode(pcm)
    back = decode(data)
    noise = sum((a - b) ** 2 for a, b in zip(pcm, back)) or 1
    signal = sum(a * a for a in pcm)
    import math
    snr = 10 * math.log10(signal / noise)

    lines = [", ".join(f"0x{b:02x}" for b in data[i:i + 20]) for i in range(0, len(data), 20)]
    (out_dir / "voice_clip_data.c").write_text(
        "// Generated by tools/make_voice_clip.py. Do not edit.\n"
        '#include "voice_clip_data.h"\n\n'
        f"const char kVoiceClipText[] = \"{SCRIPT}\";\n\n"
        f"const size_t kVoiceClipBytes = {len(data)};\n\n"
        "const uint8_t kVoiceClipAdpcm[] = {\n    " + ",\n    ".join(lines) + "\n};\n")
    (out_dir / "voice_clip_data.h").write_text(
        "// Generated by tools/make_voice_clip.py. Do not edit.\n"
        f"// A {len(pcm) / RATE:.1f} second recording of the macOS voice \"{VOICE}\" reading an EMS-style report,\n"
        "// 16 kHz mono, stored as IMA ADPCM (see lib/earshot_core/src/voice_clip.h).\n"
        "#pragma once\n#include <stddef.h>\n#include <stdint.h>\n\n"
        "#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n"
        "extern const uint8_t kVoiceClipAdpcm[];\n"
        "extern const size_t kVoiceClipBytes;\n"
        "extern const char kVoiceClipText[];  // the words spoken\n\n"
        "#ifdef __cplusplus\n}\n#endif\n")
    ref = root / "build" / "voice_clip.wav"
    ref.parent.mkdir(exist_ok=True)
    with wave.open(str(ref), "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(RATE); w.writeframes(back.tobytes())
    print(f"{len(pcm) / RATE:.1f} s, {len(data):,} bytes of ADPCM, {snr:.1f} dB signal-to-noise after decoding")
    print(f"wrote {out_dir}/voice_clip_data.c and .h; decoded copy for listening: {ref}")


if __name__ == "__main__":
    sys.exit(main())
