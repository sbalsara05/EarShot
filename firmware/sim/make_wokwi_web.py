#!/usr/bin/env python3
"""Package the firmware for the Wokwi website (wokwi.com), which builds from source.

The website has no PlatformIO project, so this folds the firmware into the files a Wokwi web
project uses:

  build/wokwi_web/sketch.ino      tiny: setup() and loop() only
  build/wokwi_web/earshot.h       the whole firmware (core + ESP32 hardware layer) in one header
  build/wokwi_web/diagram.json    virtual board: button on G41, 12-pixel ring on G2
  build/wokwi_web/libraries.txt   Adafruit NeoPixel

To use by hand: open https://wokwi.com/projects/new/esp32-s3, paste sketch.ino and diagram.json
into their tabs, add a file named earshot.h (arrow next to "Library Manager" > New file) and paste
it in, add "Adafruit NeoPixel" in the Library Manager, then press the green play button.

The Wokwi build uses a generated tone for the microphone (Wokwi cannot simulate I2S on the
ESP32-S3). On the website the virtual board cannot reach a tablet on your laptop, so this build
is standalone: it never looks for the tablet and the ring shows the consent state steadily. The
VS Code extension can reach the tablet (see README).
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
CORE = ROOT / "lib" / "earshot_core" / "src"
OUT = ROOT / "build" / "wokwi_web"

HEADERS = ["button.h", "clip_fsm.h", "hal.h", "link.h", "ws_client.h", "ws_link.h", "protocol.h",
           "audio_encoder.h", "clip_app.h"]
SOURCES = ["button.cpp", "clip_fsm.cpp", "ws_client.cpp", "ws_link.cpp", "protocol.cpp", "clip_app.cpp"]
OURS = set(HEADERS) | {"config.h", "config.example.h", "build_config.h"}


def strip(text: str) -> str:
    out = []
    for line in text.splitlines():
        m = re.match(r'\s*#include\s+"([^"]+)"', line)
        if m and m.group(1) in OURS:
            continue
        if line.strip() == "#pragma once":
            continue
        out.append(line)
    return "\n".join(out).strip() + "\n"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    parts = ["// Earshot clip firmware, folded into one file for the Wokwi website.\n"
             "// Generated by sim/make_wokwi_web.py. Do not edit; edit the sources and regenerate.\n"
             "#pragma once\n#define EARSHOT_WOKWI 1\n"
             "#define EARSHOT_STANDALONE 1  // wokwi.com cannot reach a tablet: no link, no blinking\n"
             "#include <Arduino.h>\n"]
    for name in HEADERS + SOURCES:
        parts.append(f"\n// ======================= {name}\n" + strip((CORE / name).read_text()))
    parts.append("\n// ======================= config.example.h\n"
                 + strip((ROOT / "include" / "config.example.h").read_text()))
    parts.append("\n// ======================= build_config.h\n"
                 + strip((ROOT / "src" / "build_config.h").read_text()))
    main_cpp = strip((ROOT / "src" / "main.cpp").read_text())
    main_cpp = main_cpp.replace("void setup() {", "void earshotSetup() {")
    main_cpp = main_cpp.replace("void loop() {", "void earshotLoop() {")
    assert "earshotSetup" in main_cpp and "earshotLoop" in main_cpp
    parts.append("\n// ======================= main.cpp\n" + main_cpp)
    (OUT / "earshot.h").write_text("".join(parts))

    (OUT / "sketch.ino").write_text(
        '// Earshot clip firmware on Wokwi. All the code is in earshot.h.\n'
        '#include "earshot.h"\n\n'
        'void setup() { earshotSetup(); }\n'
        'void loop() { earshotLoop(); }\n')

    (OUT / "libraries.txt").write_text("Adafruit NeoPixel\n")

    diagram = json.loads((ROOT / "diagram.json").read_text())
    for part in diagram["parts"]:
        if part["id"] == "esp":
            part["attrs"] = {}  # the website builds with default options: serial on UART0
    diagram["connections"] = [
        ["esp:TX", "$serialMonitor:RX", "", []],
        ["esp:RX", "$serialMonitor:TX", "", []],
    ] + diagram["connections"]
    (OUT / "diagram.json").write_text(json.dumps(diagram, indent=2) + "\n")

    for f in sorted(OUT.iterdir()):
        print(f"{f.relative_to(ROOT)}  ({f.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
